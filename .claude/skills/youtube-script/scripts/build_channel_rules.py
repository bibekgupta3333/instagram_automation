#!/usr/bin/env python3
"""Regenerate references/channel-rules.md from brand_packs/*.yaml.

    uv run python .claude/skills/youtube-script/scripts/build_channel_rules.py          # write
    uv run python .claude/skills/youtube-script/scripts/build_channel_rules.py --check  # diff only

The brand packs stay the source of truth; this file is a reading aid for the skill.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[4]
BRAND_DIR = REPO_ROOT / "brand_packs"
OUT = Path(__file__).resolve().parents[1] / "references" / "channel-rules.md"


def _common(packs: list[dict], key: str) -> list[str]:
    first = packs[0].get(key, [])
    return [x for x in first if all(x in p.get(key, []) for p in packs)]


def render(brand_dir: Path = BRAND_DIR) -> str:
    packs = [yaml.safe_load(p.read_text()) | {"slug": p.stem}
             for p in sorted(brand_dir.glob("*.yaml"))]
    common_red = _common(packs, "red_lines")
    common_banned = _common(packs, "banned_templates")
    lines = [
        "# Channel Rules",
        "",
        ("<!-- GENERATED by scripts/build_channel_rules.py from brand_packs/*.yaml."
        " Do not edit by hand; edit the brand pack and regenerate. -->"),
        "",
        f"Summary of the {len(packs)} brand packs. The YAML files are the source of truth and the",
        "pipeline lint (`studio/stages/policy.py`) enforces `red_lines` and `banned_templates`.",
        "Every channel is faceless with an AI-generated voice, Not made for kids and AI-disclosed.",
        "",
        "## Rules for every channel",
        "",
        "Red lines:",
        *(f"- {r}" for r in common_red),
        "",
        "Banned phrases (any field, case-insensitive): "
        + ", ".join(f"`{b}`" for b in common_banned) + ".",
        "",
        "## Channels",
    ]
    for p in packs:
        voice = p.get("voice", {})
        extra_red = [r for r in p.get("red_lines", []) if r not in common_red]
        extra_banned = [b for b in p.get("banned_templates", []) if b not in common_banned]
        lines += [
            "",
            f"### {p['name']} (`{p['slug']}`, {p.get('handle', '')})",
            "",
            f"- **Niche:** {p.get('niche', '')}",
            (f"- **Voice:** Kokoro `{voice.get('voice', '')}` at speed {voice.get('speed', 1.0)}"
            f"{' · accuracy-critical' if p.get('accuracy_critical') else ''}"),
            (f"- **Visual style** (appended to every image prompt; do not paste it): "
            f"{p.get('style_prompt', '')}"),
            ("- **Hook styles** (patterns, not lines to copy; examples with numbers still need "
            "sources):"),
            *(f"  - {h}" for h in p.get("hook_styles", [])),
        ]
        if extra_red:
            lines += ["- **Channel red lines:**", *(f"  - {r}" for r in extra_red)]
        if extra_banned:
            lines.append("- **Extra banned phrases:** "
                         + ", ".join(f"`{b}`" for b in extra_banned))
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Exit 1 if the file is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"STALE: {OUT} (run without --check to regenerate)")
            return 1
        print("up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
